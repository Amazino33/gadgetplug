    <p class="ref">
        {{ $statement->reference }} · generated by {{ $statement->generatedBy->name }}
        on {{ $statement->generated_at->format('d M Y, g:ia') }}
    </p>

    {{-- The number the settlement conversation is actually about, given its own
         box so nobody has to hunt for it among figures that merely support it. --}}
